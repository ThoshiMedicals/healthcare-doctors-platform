/** Idempotent seed of AI placeholders for PE + lifestyle + sample video/transcript/quote. */
export async function seedAttractionAssetPlaceholders(clinicId: string, ownerUserId?: string) {
  const created: string[] = [];

  for (const pe of LAUNCH_STILLS) {
    const path = `/assets/attraction/placeholders/${pe.file}`;
    await upsertLibraryAsset({
      clinicId,
      assetId: pe.assetId,
      kind: "image",
      title: `${pe.module} — ${pe.assetId}`,
      status: "catalogued",
      storagePath: path,
      replaceablePath: `attraction-assets/images/masters/${pe.planRef}__${pe.assetId}__master.webp`,
      placeholderKind: "ai",
      mime: "image/jpeg",
      width: 1200,
      height: 675,
      altText: pe.alt,
      caption: pe.caption,
      scene: pe.scene,
      surfaceHints: ["practice_experience", "opportunity_pack", "gp_opportunities"],
      moduleHints: [pe.module],
      sourceShotId: pe.planRef,
      relatedDocumentKind: "practice_experience",
      rightsClass: "ai_placeholder",
      aiPolicy: "aiPolicy" in pe && pe.aiPolicy ? pe.aiPolicy : "ai_ok",
      derivativesJson: defaultImageDerivatives(pe.assetId),
      ownerUserId,
    });
    created.push(pe.assetId);

    // Keep hub-facing aliases registered for module heroes
    if ("hubFile" in pe && pe.hubFile) {
      await upsertLibraryAsset({
        clinicId,
        assetId: `${pe.assetId}-HUB`,
        kind: "image",
        title: `Hub hero alias — ${pe.module}`,
        status: "catalogued",
        storagePath: `/assets/practice-experience/${pe.hubFile}`,
        replaceablePath: path,
        placeholderKind: "ai",
        mime: "image/jpeg",
        altText: pe.alt,
        caption: `Hub path alias for ${pe.assetId}`,
        scene: pe.scene,
        surfaceHints: ["practice_experience"],
        moduleHints: [pe.module],
        sourceShotId: pe.planRef,
        parentAssetId: pe.assetId,
        rightsClass: "ai_placeholder",
        aiPolicy: "ai_ok",
        ownerUserId,
      });
      created.push(`${pe.assetId}-HUB`);
    }
  }

  await upsertLibraryAsset({
    clinicId,
    assetId: "VID-TD-01",
    kind: "video",
    title: "Typical day overview (placeholder)",
    status: "catalogued",
    storagePath: "/assets/attraction/placeholders/posters/VID-TD-01__poster__2026-11.jpg",
    replaceablePath: "attraction-assets/video/masters/VID-TD-01__typical-day__master.mp4",
    placeholderKind: "ai",
    mime: "video/mp4",
    durationSec: 90,
    altText: "Placeholder poster for practice day overview video",
    caption: "AI/pending video placeholder — replace with staff-consented walkthrough.",
    scene: "consulting_room",
    surfaceHints: ["practice_experience", "gp_opportunities"],
    moduleHints: ["typical_day"],
    sourceShotId: "VID-TD-01",
    relatedDocumentKind: "practice_experience",
    rightsClass: "ai_placeholder",
    aiPolicy: "ai_assist",
    ownerUserId,
  });
  created.push("VID-TD-01");

  for (const vid of [
    "VID-NU-01",
    "VID-RX-01",
    "VID-TM-01",
    "VID-CM-01",
    "VID-CO-01",
    "VID-FS-01",
    "VID-LS-01",
  ] as const) {
    await upsertLibraryAsset({
      clinicId,
      assetId: vid,
      kind: "video",
      title: `${vid} placeholder`,
      status: "catalogued",
      storagePath: null,
      replaceablePath: `attraction-assets/video/masters/${vid}__master.mp4`,
      placeholderKind: "ai",
      mime: "video/mp4",
      caption: `Video placeholder — see asset-inventory.json beats for ${vid}.`,
      altText: `Video placeholder ${vid}`,
      surfaceHints: ["practice_experience"],
      rightsClass: "ai_placeholder",
      aiPolicy: "ai_assist",
      relatedDocumentKind: "practice_experience",
      ownerUserId,
    });
    created.push(vid);
  }

  await upsertLibraryAsset({
    clinicId,
    assetId: "TRN-TD-01",
    kind: "transcript",
    title: "Typical day video transcript (placeholder)",
    status: "catalogued",
    storagePath: null,
    replaceablePath: "attraction-assets/transcripts/TRN-TD-01__typical-day.vtt",
    placeholderKind: "ai",
    mime: "text/vtt",
    caption: "Transcript placeholder bound to VID-TD-01",
    altText: "Transcript for typical day overview video",
    scene: "consulting_room",
    surfaceHints: ["practice_experience"],
    moduleHints: ["typical_day"],
    transcriptOfAssetId: "VID-TD-01",
    parentAssetId: "VID-TD-01",
    relatedDocumentKind: "practice_experience",
    rightsClass: "ai_placeholder",
    aiPolicy: "ai_ok",
    ownerUserId,
  });
  created.push("TRN-TD-01");

  await upsertLibraryAsset({
    clinicId,
    assetId: "QT-PE-TD-01",
    kind: "quote",
    title: "Typical day pull-quote placeholder",
    status: "catalogued",
    storagePath: null,
    replaceablePath: "attraction-assets/quotes/QT-PE-TD-01.json",
    placeholderKind: "ai",
    quoteText:
      "The book mixes acute and review work; notes stay with the session so the next visit has context.",
    caption: "Composite placeholder quote — replace via Story Capture consented version.",
    altText: "Pull quote about a typical consulting day",
    scene: "quote_card",
    surfaceHints: ["practice_experience", "gp_opportunities", "opportunity_pack"],
    moduleHints: ["typical_day", "doctor_voices"],
    relatedDocumentKind: "practice_experience",
    relatedStoryRef: "gp-story-capture:inventory",
    rightsClass: "composite_labelled",
    aiPolicy: "ai_ok",
    personaHints: ["established"],
    ownerUserId,
  });
  created.push("QT-PE-TD-01");

  const clinic = await prisma.clinic.findUnique({ where: { id: clinicId }, select: { slug: true } });

  return {
    clinicSlug: clinic?.slug,
    createdAssetIds: created,
    count: created.length,
    inventory: "docs/proposals/gp-attraction-visual-asset-plan/asset-inventory.json",
  };
}
